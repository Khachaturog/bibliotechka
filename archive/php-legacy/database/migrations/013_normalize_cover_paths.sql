-- Миграция: Нормализация путей к обложкам в таблице data (добавление / в начало)
-- Обновляет все относительные пути к обложкам, делая их абсолютными
-- Это необходимо для правильной работы на страницах с красивыми URL типа /card/...

USE bibliotechka;

-- Обновляем cover в таблице data
-- Добавляем / в начало, если путь не пустой и не начинается с /
UPDATE `data` 
SET `cover` = CONCAT('/', `cover`)
WHERE `cover` IS NOT NULL 
  AND `cover` != '' 
  AND `cover` NOT LIKE '/%';

